def quadrature_2d(order: int) -> Tuple[np.ndarray, np.ndarray]:
    """Return ``(xq2, wq2)`` for quadrature *order* (1-4).

    ``order`` is the ``quad`` constructor argument: ``quadrature_2d(p + 1)``
    is the rule for polynomial order ``p``.

    Raises
    ------
    ValueError
        For any order not implemented.
    """
    try:
        points, weights = _RULES[int(order)]
    except (KeyError, ValueError):
        raise ValueError(
            f"quadrature order {order!r} is not implemented; supports orders "
            f"1-{MAX_ORDER}"
        ) from None
    return points.copy(), weights.copy()


def quadrature_3d(order: int) -> Tuple[np.ndarray, np.ndarray]:
    """Return ``(xq3, wq3)`` for tetrahedral quadrature *order* (1-4).

    The reference tetrahedron is ``(0,0,0), (1,0,0), (0,1,0), (0,0,1)``.  The
    weights sum to ``1/6``, so ``sum(w * detJ)`` is the physical-volume
    integral with ``detJ`` the raw determinant of the coordinate map (the same
    convention as :func:`quadrature_2d`).

    Raises
    ------
    ValueError
        For any order not implemented.
    """
    try:
        points = X3[int(order)]
        weights = W3[int(order)]
    except (KeyError, ValueError):
        raise ValueError(
            f"quadrature order {order!r} is not implemented; supports orders "
            f"1-{MAX_ORDER}"
        ) from None
    return points.copy(), weights.copy()
